"""Generate / verify js/natural_stimuli_vN.js (N in VERSIONS) from the canonical
stimulus CSVs in the modulating_beliefs_via_alternatives repo (read-only --
this script never writes there).

Sources (merged on `id`):
  alternatives_vN.csv        id, Context, Speaker, [U0 (v4+),] U1 (weak), U2 (strong),
                             Question (a template, e.g. "How likely is it that {}?")
  belief_verbalizations.csv  id, Belief, ... -- `Belief` fills the `{}` slot

  v2 -> js/natural_stimuli_v2.js  (designs 0-2)
  v4 -> js/natural_stimuli_v4.js  (design 3; adds u0_utterance)

Usage:
  python3 scripts/sync_natural_stimuli.py            # (re)write js/natural_stimuli_v2.js
  python3 scripts/sync_natural_stimuli.py --check    # exit 1 if js/ is stale

--check fails if:
  * any js/natural_stimuli_vN.js differs from what the current CSVs generate, or
  * a newer alternatives_vN.csv (N > max(VERSIONS)) exists in the data dir.

Data dir defaults to DEFAULT_DATA_DIR; override with --data-dir or the
ALTERNATIVES_DATA_DIR environment variable.
"""
import argparse
import csv
import difflib
import hashlib
import json
import os
import re
import sys

VERSIONS = (2, 4)
DEFAULT_DATA_DIR = "/home/mila/c/cesare.spinoso/modulating_beliefs_via_alternatives/src/data"
HERE = os.path.dirname(os.path.abspath(__file__))


def out_path(version):
    return os.path.normpath(os.path.join(HERE, "..", "js", f"natural_stimuli_v{version}.js"))


def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def read_csv(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def latest_version(data_dir):
    versions = []
    for name in os.listdir(data_dir):
        m = re.fullmatch(r"alternatives_v(\d+)\.csv", name)
        if m:
            versions.append(int(m.group(1)))
    return max(versions) if versions else None


def build(data_dir, version):
    alt_path = os.path.join(data_dir, f"alternatives_v{version}.csv")
    belief_path = os.path.join(data_dir, "belief_verbalizations.csv")
    alts = read_csv(alt_path)
    beliefs = {r["id"]: r for r in read_csv(belief_path)}

    alt_ids = [r["id"] for r in alts]
    if len(set(alt_ids)) != len(alt_ids):
        raise ValueError(f"Duplicate ids in {alt_path}")
    missing = [i for i in alt_ids if i not in beliefs]
    if missing:
        raise ValueError(f"ids missing from {belief_path}: {missing}")

    items = []
    for r in alts:
        template = r["Question"].strip()
        if template.count("{}") != 1:
            raise ValueError(f"{r['id']}: Question must contain exactly one '{{}}': {template!r}")
        belief = beliefs[r["id"]]["Belief"].strip()
        item = {
            "scenario_id": r["id"],
            "scenario": r["Context"].strip(),
            "mainName": r["Speaker"].strip(),
        }
        if version >= 4:
            item["u0_utterance"] = r["U0"].strip() or None
        item.update({
            "weak_utterance": r["U1"].strip(),
            "strong_utterance": r["U2"].strip(),
            "question_template": template,
            "belief": belief,
            "question": template.replace("{}", belief),
        })
        items.append(item)

    source = {
        "alternatives_file": os.path.basename(alt_path),
        "alternatives_version": version,
        "alternatives_sha256": sha256(alt_path),
        "beliefs_file": os.path.basename(belief_path),
        "beliefs_sha256": sha256(belief_path),
    }
    return render(items, source, version)


def render(items, source, version):
    var = f"natural_stimuli_v{version}"
    src_var = "natural_stimuli_source" if version == 2 else f"{var}_source"
    u0_note = "u0_utterance = U0 (null if blank), " if version >= 4 else ""
    return (
        "// AUTO-GENERATED by scripts/sync_natural_stimuli.py -- DO NOT EDIT BY HAND.\n"
        "// Source: modulating_beliefs_via_alternatives/src/data/"
        f"{source['alternatives_file']} + {source['beliefs_file']} (merged on id).\n"
        "// Regenerate:  python3 scripts/sync_natural_stimuli.py\n"
        "// Verify:      python3 scripts/sync_natural_stimuli.py --check\n"
        "//\n"
        f"// {u0_note}weak_utterance = U1, strong_utterance = U2; question = Question template\n"
        "// with `{}` filled by the (non-negated) Belief.\n\n"
        f"var {src_var} = {json.dumps(source, indent=2, ensure_ascii=False)};\n\n"
        f"var {var} = {json.dumps(items, indent=2, ensure_ascii=False)};\n\n"
        "if (typeof module !== 'undefined' && module.exports) {\n"
        f"  module.exports = {{ {var}: {var}, {src_var}: {src_var} }};\n"
        "}\n"
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify only; exit 1 if stale")
    ap.add_argument("--data-dir", default=os.environ.get("ALTERNATIVES_DATA_DIR", DEFAULT_DATA_DIR))
    args = ap.parse_args()

    latest = latest_version(args.data_dir)
    if latest is None:
        sys.exit(f"ERROR: no alternatives_v*.csv found in {args.data_dir}")
    if latest > max(VERSIONS):
        sys.exit(
            f"ERROR: latest stimuli file is alternatives_v{latest}.csv but this script targets "
            f"{VERSIONS}. Add it to VERSIONS in {os.path.basename(__file__)} "
            f"(and the <script> tag / experiment.js), then regenerate."
        )

    stale = False
    for version in VERSIONS:
        expected = build(args.data_dir, version)
        path = out_path(version)
        if not args.check:
            with open(path, "w", encoding="utf-8") as f:
                f.write(expected)
            print(f"Wrote {path}")
            continue
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if current == expected:
            print(f"OK: {os.path.relpath(path)} is up to date with alternatives_v{version}.csv")
            continue
        stale = True
        sys.stdout.writelines(difflib.unified_diff(
            current.splitlines(keepends=True), expected.splitlines(keepends=True),
            fromfile=f"{os.path.relpath(path)} (current)", tofile=f"generated from alternatives_v{version}.csv",
        ))
        print(f"\nSTALE: {os.path.relpath(path)} does not match alternatives_v{version}.csv")
    if stale:
        sys.exit("Run: python3 scripts/sync_natural_stimuli.py")


if __name__ == "__main__":
    main()
